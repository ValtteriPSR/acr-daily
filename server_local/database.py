"""Database access for SQLite installations and durable PostgreSQL hosting.

The compatibility layer covers the SQL used by this application. It is not a
general SQL translator. Results are buffered before pooled connections return.
"""
from collections import deque
import os
import re
import sqlite3
import threading


class Row(dict):
    def __getitem__(self, key):
        return list(self.values())[key] if isinstance(key, int) else super().__getitem__(key)


class Result:
    def __init__(self, rows=(), rowcount=0, lastrowid=None):
        self.rows = deque(rows)
        self.rowcount = rowcount
        self.lastrowid = lastrowid

    def fetchone(self):
        return self.rows.popleft() if self.rows else None

    def fetchall(self):
        rows = list(self.rows)
        self.rows.clear()
        return rows

    def __iter__(self):
        while self.rows:
            yield self.rows.popleft()


def postgres_sql(sql):
    """Translate only the SQLite constructs present in the club's queries."""
    sql = sql.strip().rstrip(';')
    if re.fullmatch(r'BEGIN IMMEDIATE', sql, re.I):
        return 'BEGIN', False
    pragma = re.fullmatch(r'PRAGMA table_info\(([a-z_]+)\)', sql, re.I)
    if pragma:
        table = pragma.group(1)
        return ("SELECT column_name AS name FROM information_schema.columns "
                f"WHERE table_schema=current_schema() AND table_name='{table}' "
                "ORDER BY ordinal_position"), False
    sql = re.sub(r'\bid INTEGER PRIMARY KEY(?: AUTOINCREMENT)?\b',
                 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql)
    sql = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', sql)
    if re.match(r'INSERT OR IGNORE\b', sql, re.I):
        sql = re.sub(r'^INSERT OR IGNORE', 'INSERT', sql, flags=re.I)
        sql += ' ON CONFLICT DO NOTHING'
    if re.match(r'INSERT OR REPLACE INTO launch_leases\b', sql, re.I):
        sql = re.sub(r'^INSERT OR REPLACE', 'INSERT', sql, flags=re.I)
        sql += ' ON CONFLICT (player_id) DO UPDATE SET expires=EXCLUDED.expires'
    generated = bool(re.match(
        r'INSERT INTO (players|club_members|season_divisions|season_teams|admin_audit)\b', sql, re.I))
    if generated:
        sql += ' RETURNING id'
    # Preserve quoted text, including question marks inside SQL string literals.
    sql = re.sub(r"'(?:''|[^'])*'|\?", lambda m: '%s' if m[0] == '?' else m[0], sql)
    return sql, generated


class PostgresDatabase:
    def __init__(self, url, *, schema=None):
        import psycopg
        from psycopg_pool import ConnectionPool
        self.psycopg = psycopg
        self.local = threading.local()
        kwargs = {'autocommit': True, 'prepare_threshold': None, 'connect_timeout': 15}
        if schema:
            if not re.fullmatch(r'[a-z_][a-z0-9_]*', schema):
                raise ValueError('Invalid database schema')
            kwargs['options'] = '-c search_path=' + schema
        self.pool = ConnectionPool(url, min_size=0, max_size=4, max_idle=60,
                                   timeout=30, kwargs=kwargs,
                                   check=ConnectionPool.check_connection, open=True)

    @property
    def in_transaction(self):
        return getattr(self.local, 'connection', None) is not None

    def _execute(self, connection, sql, params, generated):
        try:
            with connection.cursor() as cursor:
                cursor.execute(sql, params if params else None)
                rows = ([Row(zip((col.name for col in cursor.description), values))
                         for values in cursor.fetchall()] if cursor.description else [])
                lastrowid = rows[0]['id'] if generated and rows else None
                return Result(rows, cursor.rowcount, lastrowid)
        except self.psycopg.IntegrityError as exc:
            # Existing business rules already map SQLite integrity failures to 409.
            raise sqlite3.IntegrityError(str(exc)) from exc

    def execute(self, sql, params=()):
        sql, generated = postgres_sql(sql)
        if sql == 'BEGIN':
            if self.in_transaction:
                raise RuntimeError('Nested transaction is not supported')
            connection = self.pool.getconn()
            try:
                result = self._execute(connection, sql, (), False)
                self.local.connection = connection
                return result
            except Exception:
                self.pool.putconn(connection)
                raise
        connection = getattr(self.local, 'connection', None)
        if connection is not None:
            if sql in ('COMMIT', 'ROLLBACK'):
                try:
                    return self._execute(connection, sql, (), False)
                finally:
                    self.local.connection = None
                    self.pool.putconn(connection)
            return self._execute(connection, sql, params, generated)
        with self.pool.connection() as connection:
            return self._execute(connection, sql, params, generated)

    def executescript(self, script):
        # Application schema scripts contain simple DDL and no semicolons in literals.
        for statement in script.split(';'):
            if statement.strip():
                self.execute(statement)

    def close(self):
        if self.in_transaction:
            self.execute('ROLLBACK')
        self.pool.close()


def connect_database(path, *, url=None):
    url = url or os.environ.get('DATABASE_URL', '')
    if url:
        return PostgresDatabase(url)
    db = sqlite3.connect(path, check_same_thread=False, isolation_level=None)
    db.row_factory = sqlite3.Row
    db.execute('PRAGMA journal_mode=WAL')
    db.execute('PRAGMA foreign_keys=ON')
    return db
